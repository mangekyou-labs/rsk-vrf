"""Emit src/witnet/WitnetVectors.sol from witnet/vrf-solidity test/data.json (first valid
fastVerify vector, message "sample"). Usage: python3 -I scripts/gen_witnet_vectors.py <probe_root> <data.json>
data.json is treated as untrusted data: values are parsed as hex integers only."""
import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import vrflib as L  # noqa: E402


def main():
    root, path = sys.argv[1], sys.argv[2]
    with open(path) as f:
        d = json.load(f)
    v = d["fastVerify"]["valid"][0]
    pi = bytes.fromhex(v["pi"][2:])
    assert len(pi) == 81
    gamma = L.decompress(pi[:33])
    c = int.from_bytes(pi[33:49], "big")
    s = int.from_bytes(pi[49:], "big")
    pk = (int(v["publicKey"]["x"], 16), int(v["publicKey"]["y"], 16))
    assert L.on_curve(pk) and L.on_curve(gamma)
    msg = bytes.fromhex(v["message"][2:])
    vals = {
        "PK_X": pk[0], "PK_Y": pk[1], "GAMMA_X": gamma[0], "GAMMA_Y": gamma[1], "C": c, "S": s,
        "U_X": int(v["uPoint"]["x"], 16), "U_Y": int(v["uPoint"]["y"], 16),
        "SH_X": int(v["vComponents"]["sH"]["x"], 16), "SH_Y": int(v["vComponents"]["sH"]["y"], 16),
        "CG_X": int(v["vComponents"]["cGamma"]["x"], 16), "CG_Y": int(v["vComponents"]["cGamma"]["y"], 16),
    }
    lines = ["// SPDX-License-Identifier: MIT",
             "// GENERATED by scripts/gen_witnet_vectors.py from witnet/vrf-solidity@653dc85 test/data.json",
             "pragma solidity >=0.5.3 <0.7.0;", "", "contract WitnetVectors {"]
    for k, x in vals.items():
        lines.append(f"  uint256 internal constant {k} = 0x{x:064x};")
    lines.append(f"  bytes internal constant MESSAGE = hex\"{msg.hex()}\";")
    lines.append("}")
    out = os.path.join(root, "src", "witnet", "WitnetVectors.sol")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", out, "message", msg)


if __name__ == "__main__":
    main()
